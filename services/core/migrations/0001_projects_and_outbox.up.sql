-- Schema "core", owned by pf_core_owner. The runtime role pf_core receives
-- only the table privileges it needs and can never run DDL.

CREATE TABLE core.projects (
    id          uuid        PRIMARY KEY,                -- UUIDv7, generated by pf-core
    slug        text        NOT NULL
                CHECK (slug ~ '^[a-z][a-z0-9-]{1,38}[a-z0-9]$'),
    name        text        NOT NULL
                CHECK (char_length(name) BETWEEN 1 AND 100),
    description text        NOT NULL DEFAULT ''
                CHECK (char_length(description) <= 500),
    created_by  text        NOT NULL,                   -- OIDC subject
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX projects_slug_key ON core.projects (slug);

-- Transactional outbox: a row is written in the same transaction as the
-- state change it describes. A relay publishes unpublished rows to the
-- event bus (later milestone) and sets published_at.
CREATE TABLE core.outbox (
    id           uuid        PRIMARY KEY,               -- CloudEvents id
    subject      text        NOT NULL,                  -- e.g. pf.core.evt.project.created
    event_type   text        NOT NULL,                  -- e.g. parallelf.core.v1.ProjectCreated
    payload      bytea       NOT NULL,                  -- protojson-encoded message
    headers      jsonb       NOT NULL DEFAULT '{}',     -- CloudEvents attributes
    created_at   timestamptz NOT NULL DEFAULT now(),
    published_at timestamptz
);

CREATE INDEX outbox_unpublished ON core.outbox (created_at) WHERE published_at IS NULL;

GRANT SELECT, INSERT, UPDATE, DELETE ON core.projects TO pf_core;
GRANT SELECT, INSERT, UPDATE ON core.outbox TO pf_core;
