// Package suricata runs Suricata on the networks ParallelF owns: the VPN
// interface and the Cloud bridges (pfbr-*). It writes a complete,
// self-contained configuration, tests it before every start, and restarts
// the engine when the set of monitored interfaces changes.
package suricata

import (
	"context"
	"errors"
	"fmt"
	"log/slog"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
	"sync"
	"syscall"
	"time"
)

// CanaryRules are ParallelF's own signatures. They detect deliberate test
// traffic only, so the IDS path can be verified end to end without
// generating anything harmful.
const CanaryRules = `# ParallelF canary signatures: match only deliberate self-test traffic.
alert http any any -> any any (msg:"PARALLELF canary: IDS self-test URI"; flow:established,to_server; http.uri; content:"/pf-ng-ids-canary"; sid:9100001; rev:1; classtype:misc-activity;)
alert dns any any -> any any (msg:"PARALLELF canary: IDS self-test DNS query"; dns.query; content:"pf-ng-ids-canary"; nocase; sid:9100002; rev:1; classtype:misc-activity;)
`

var ifacePattern = regexp.MustCompile(`^[a-zA-Z0-9_.-]{1,15}$`)

// Interfaces returns the monitored interfaces present on the host, sorted:
// vpnIface and every Cloud bridge.
func Interfaces(sysClassNet, vpnIface string) []string {
	entries, err := os.ReadDir(sysClassNet)
	if err != nil {
		return nil
	}
	var out []string
	for _, e := range entries {
		name := e.Name()
		if (name == vpnIface || strings.HasPrefix(name, "pfbr-")) && ifacePattern.MatchString(name) {
			out = append(out, name)
		}
	}
	slices.Sort(out)
	return out
}

// RenderConfig returns a complete suricata.yaml for ifaces.
