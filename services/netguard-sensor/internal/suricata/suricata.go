// Supervisor runs one Suricata process.
type Supervisor struct {
	Binary   string
	DataDir  string
	ETRules  string // optional extra rules file (ET Open via suricata-update)
	Logger   *slog.Logger
	mu       sync.Mutex
	cmd      *exec.Cmd
	ifaces   []string
	exited   chan struct{}
	lastErr  string
	startErr error
}

// LogDir is where Suricata writes eve.json.
func (s *Supervisor) LogDir() string { return filepath.Join(s.DataDir, "suricata") }

// EvePath is the EVE file the sensor tails.
func (s *Supervisor) EvePath() string { return filepath.Join(s.LogDir(), "eve.json") }

// Version returns the engine's version line.
func (s *Supervisor) Version(ctx context.Context) (string, error) {
	out, err := exec.CommandContext(ctx, s.Binary, "-V").CombinedOutput()
	if err != nil {
		return "", fmt.Errorf("suricata -V: %w", err)
	}
	v := strings.TrimSpace(string(out))
	v = strings.TrimPrefix(v, "This is ")
	return strings.TrimSuffix(v, " RELEASE"), nil
}

// Err is the last engine problem, or empty while it runs.
func (s *Supervisor) Err() string {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.lastErr
}

// Ensure keeps Suricata running on exactly ifaces.
func (s *Supervisor) Ensure(ctx context.Context, ifaces []string) error {
	s.mu.Lock()
	running := s.cmd != nil && s.exited != nil && !isClosed(s.exited)
	same := slices.Equal(ifaces, s.ifaces)
	s.mu.Unlock()
	if running && same {
		return nil
	}
	s.Stop()
	if len(ifaces) == 0 {
		s.setErr("no monitored interface exists yet (wg-pf0 or pfbr-*)")
		return nil
	}
	if err := s.start(ctx, ifaces); err != nil {
		s.setErr(err.Error())
		return err
	}
	return nil
}

func isClosed(ch chan struct{}) bool {
	select {
	case <-ch:
		return true
	default:
		return false
	}
}

func (s *Supervisor) setErr(msg string) {
	s.mu.Lock()
	s.lastErr = msg
	s.mu.Unlock()
}

func (s *Supervisor) start(ctx context.Context, ifaces []string) error {
	if err := os.MkdirAll(s.LogDir(), 0o750); err != nil {
		return err
	}
	cfg, err := RenderConfig(ifaces, s.LogDir())
	if err != nil {
		return err
	}
	cfgPath := filepath.Join(s.DataDir, "suricata.yaml")
	if err := os.WriteFile(cfgPath, cfg, 0o640); err != nil {
		return err
	}
	rules := CanaryRules
	if s.ETRules != "" {
		if extra, err := os.ReadFile(s.ETRules); err == nil {
			rules += "\n" + string(extra)
		} else {
			s.Logger.Warn("extra rules not loaded", slog.String("path", s.ETRules), slog.String("error", err.Error()))
		}
	}
	rulesPath := filepath.Join(s.DataDir, "parallelf.rules")
	if err := os.WriteFile(rulesPath, []byte(rules), 0o640); err != nil {
		return err
	}
	if out, err := exec.CommandContext(ctx, s.Binary, "-T", "-c", cfgPath, "-S", rulesPath, "-l", s.LogDir()).CombinedOutput(); err != nil {
		return fmt.Errorf("suricata rejected its configuration: %s", tailLines(string(out), 8))
	}
	pid := filepath.Join(s.LogDir(), "suricata.pid")
	_ = os.Remove(pid)
	// Not tied to ctx: the sensor stops it explicitly, after the last read.
	cmd := exec.Command(s.Binary, "-c", cfgPath, "-S", rulesPath, "-l", s.LogDir(), "--af-packet", "--pidfile", pid)
	cmd.Stdout, cmd.Stderr = os.Stdout, os.Stderr
	if err := cmd.Start(); err != nil {
		return fmt.Errorf("start suricata: %w", err)
	}
	exited := make(chan struct{})
	go func() {
		err := cmd.Wait()
		s.mu.Lock()
		if s.cmd == cmd {
			s.lastErr = fmt.Sprintf("suricata exited: %v", err)
		}
		s.mu.Unlock()
		close(exited)
	}()
	s.mu.Lock()
	s.cmd, s.exited, s.ifaces, s.lastErr = cmd, exited, slices.Clone(ifaces), ""
	s.mu.Unlock()
	s.Logger.Info("suricata started", slog.Any("interfaces", ifaces), slog.Int("pid", cmd.Process.Pid))
	return nil
}

func tailLines(s string, n int) string {
	lines := strings.Split(strings.TrimSpace(s), "\n")
	if len(lines) > n {
		lines = lines[len(lines)-n:]
	}
	return strings.Join(lines, " | ")
}

// Stop ends the engine (SIGTERM, then SIGKILL after 15 s).
func (s *Supervisor) Stop() {
	s.mu.Lock()
	cmd, exited := s.cmd, s.exited
	s.cmd, s.ifaces = nil, nil
	s.mu.Unlock()
	if cmd == nil || cmd.Process == nil {
		return
	}
	_ = cmd.Process.Signal(syscall.SIGTERM)
	select {
	case <-exited:
	case <-time.After(15 * time.Second):
		_ = cmd.Process.Kill()
		<-exited
	}
}

// Rotate renames eve.json when it exceeds maxBytes and asks Suricata to
// reopen its logs (SIGHUP). The tailer notices the new inode.
func (s *Supervisor) Rotate(maxBytes int64) error {
	fi, err := os.Stat(s.EvePath())
	if err != nil || fi.Size() < maxBytes {
		return nil
	}
	if err := os.Rename(s.EvePath(), s.EvePath()+".1"); err != nil {
		return err
	}
	s.mu.Lock()
	cmd := s.cmd
	s.mu.Unlock()
	if cmd == nil || cmd.Process == nil {
		return errors.New("suricata is not running")
	}
	return cmd.Process.Signal(syscall.SIGHUP)
}
